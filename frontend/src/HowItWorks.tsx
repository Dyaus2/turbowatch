import type { MetricsResp } from "./api";
import { useLiveJSON } from "./replay";
import { Panel } from "./ui";

const STEPS = [
  { t: "NASA C-MAPSS", d: "Simulated turbofan run-to-failure data: 21 sensors, 3 operating settings per cycle." },
  { t: "Validate & normalise", d: "Schema checks, per-operating-regime z-scores (KMeans on settings)." },
  { t: "Causal features", d: "Rolling mean/std (5, 15), 15-cycle slope, EWM — row t only sees cycles ≤ t. Same code at train & serve time." },
  { t: "Models", d: "Gradient boosting RUL + P10/P90 quantiles · 1D-CNN (PyTorch) · Isolation Forest / autoencoder health score." },
  { t: "Calibrate & decide", d: "Platt-calibrated risk of failure ≤ 30 cycles · k-of-n alarm policy tuned on a cost matrix." },
  { t: "Explain & serve", d: "Exact TreeSHAP drivers · FastAPI · React dashboard with live replay." },
];

export function HowItWorks() {
  const { data } = useLiveJSON<MetricsResp>("/api/metrics");
  const fd1 = data?.summary?.FD001 as { table?: { metric: string; test: string; holdout: string }[]; seeds?: number[] } | undefined;
  return (
    <div className="space-y-4">
      <Panel title="Pipeline">
        <ol className="grid gap-3 md:grid-cols-3 xl:grid-cols-6">
          {STEPS.map((s, i) => (
            <li key={s.t} className="relative rounded-lg border border-slate-200 p-3 dark:border-slate-800">
              <span className="mono text-[11px] text-cyan-500">0{i + 1}</span>
              <h3 className="font-semibold">{s.t}</h3>
              <p className="mt-1 text-xs leading-relaxed text-slate-500 dark:text-slate-400">{s.d}</p>
            </li>
          ))}
        </ol>
      </Panel>

      <Panel title={`Held-out results — FD001, mean ± std over ${fd1?.seeds?.length ?? "?"} seeds`}>
        {fd1?.table ? (
          <div className="overflow-x-auto">
            <table className="w-full text-sm tick-num">
              <thead className="text-left text-[11px] uppercase tracking-wider text-slate-500">
                <tr><th className="py-2 pr-4">Metric</th><th className="py-2 pr-4">Official test set (100 engines)</th><th className="py-2">Held-out run-to-failure engines</th></tr>
              </thead>
              <tbody>
                {fd1.table.map((r) => (
                  <tr key={r.metric} className="border-t border-slate-200 dark:border-slate-800">
                    <td className="py-2 pr-4">{r.metric}</td><td className="py-2 pr-4 mono font-semibold">{r.test}</td><td className="py-2 mono">{r.holdout}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        ) : <p className="text-sm text-slate-500">Loading metrics…</p>}
        <p className="mt-3 text-xs leading-relaxed text-slate-500 dark:text-slate-400">
          Training engines are split <b>by engine</b> into fit (70%) / calibration (15%) / holdout (15%). Models are fitted on fit engines only;
          risk calibration, alarm-policy tuning and model selection use calibration engines; holdout and the official test set are used for reporting only.
          A failure is "detected" if an alarm fires while true RUL ≤ 60 and the engine reaches the 30-cycle danger zone; an alarm while true RUL &gt; 60 counts as false.
          Every number is regenerated by <span className="mono">scripts/make_results.py</span>.
        </p>
      </Panel>

      <div className="grid gap-4 md:grid-cols-2">
        <Panel title="What did not work (kept on purpose)">
          <ul className="list-disc space-y-1 pl-5 text-sm text-slate-600 dark:text-slate-300">
            <li>The autoencoder health score separates degraded from healthy cycles poorly; its cost-optimal policy alarms on every engine.</li>
            <li>The Isolation Forest risk is well calibrated but reacts late on truncated test engines (62% detection).</li>
            <li>The P10–P90 band covers the truth in ~66% of test engines (nominal 80%) — the quantile models are over-confident.</li>
          </ul>
        </Panel>
        <Panel title="Limitations">
          <ul className="list-disc space-y-1 pl-5 text-sm text-slate-600 dark:text-slate-300">
            <li>C-MAPSS is simulated: no maintenance actions, sensor faults or censoring as in real fleets.</li>
            <li>RUL is capped at 125 cycles (standard practice); early-life predictions are deliberately flat.</li>
            <li>Decision support only — not a certified maintenance or airworthiness tool.</li>
          </ul>
        </Panel>
      </div>
    </div>
  );
}
