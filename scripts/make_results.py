"""Aggregate results/runs/*.json into results/RESULTS.md and results/summary.json (mean ± std over seeds)."""
import json
from collections import defaultdict
from pathlib import Path

import numpy as np

runs = defaultdict(list)
for f in sorted(Path("results/runs").glob("*.json")):
    r = json.loads(f.read_text())
    runs[r["subset"]].append(r)


def ms(vals, fmt="{:.2f}", pct=False):
    v = np.array([x for x in vals if x is not None and np.isfinite(x)], float)
    if not len(v):
        return "n/a"
    if pct:
        v = v * 100
    s = fmt.format(v.mean())
    return s + (f" ± {fmt.format(v.std())}" if len(v) > 1 else "") + ("%" if pct else "")


summary = {}
lines = ["# Results (generated by `scripts/make_results.py` — do not edit by hand)", "",
         "All numbers are on data never used for fitting or tuning: the **official C-MAPSS test set** (RUL at the last observed cycle) "
         "and **held-out run-to-failure engines** (15% of the training engines, split by engine). Mean ± std over seeds "
         "(each seed changes the engine split and model initialisation).", ""]
for subset, rs in runs.items():
    n = len(rs)
    seeds = [r["config"]["seed"] for r in rs]
    lines += [f"## {subset} — {n} seed(s) {seeds}", "",
              f"Engines: fit {rs[0]['n_engines']['fit']}, calibration {rs[0]['n_engines']['calib']}, holdout {rs[0]['n_engines']['holdout']}, official test {rs[0]['n_engines']['test']}.", "",
              "### Remaining-useful-life (RUL, capped at 125 cycles)", "",
              "| Model | Test RMSE ↓ | Test PHM08 score ↓ | Holdout RMSE (all cycles) ↓ | P10–P90 coverage (test) |", "|---|---|---|---|---|"]
    lines.append(f"| Gradient boosting (+ quantile band) | {ms([r['gbm']['test_rmse'] for r in rs])} | {ms([r['gbm']['test_phm08'] for r in rs], '{:.0f}')} | "
                 f"{ms([r['gbm']['holdout_rmse_all_cycles'] for r in rs])} | {ms([r['gbm']['test_p10_p90_coverage'] for r in rs], '{:.0f}', pct=True)} |")
    lines.append(f"| 1D-CNN (PyTorch, {rs[0]['cnn']['epochs']} epochs, CPU) | {ms([r['cnn']['test_rmse'] for r in rs])} | {ms([r['cnn']['test_phm08'] for r in rs], '{:.0f}')} | "
                 f"{ms([r['cnn']['holdout_rmse_all_cycles'] for r in rs])} | – |")
    lines += ["", "### Alarms (policy tuned on calibration engines; failure horizon 30 cycles; alarm counted false if true RUL > 60)", "",
              "| Alarm signal | Split | Detection rate ↑ | False-alarm rate ↓ | Median lead time (cycles) | Missed failures |", "|---|---|---|---|---|---|"]
    names = {"gbm_rul": "Predicted RUL (gradient boosting)", "isolation_forest": "Health risk — Isolation Forest", "autoencoder": "Health risk — autoencoder"}
    for sig in ("gbm_rul", "isolation_forest", "autoencoder"):
        for split in ("test", "holdout"):
            ev = [r["alarms"][sig]["min_cost"][split] for r in rs]
            lines.append(f"| {names[sig]} | {split} | {ms([e['detection_rate'] for e in ev], '{:.0f}', pct=True)} | {ms([e['false_alarm_rate'] for e in ev], '{:.0f}', pct=True)} | "
                         f"{ms([e['median_lead_cycles'] for e in ev], '{:.0f}')} | {ms([e['missed'] for e in ev], '{:.1f}')} of {ev[0]['positive_engines']} |")
    lines += ["", "### Health-risk calibration (holdout engines, P(failure within 30 cycles))", "", "| Detector | Brier ↓ | ECE ↓ |", "|---|---|---|"]
    for det in ("isolation_forest", "autoencoder"):
        lines.append(f"| {names[det].split('— ')[1]} | {ms([r['health'][det]['holdout_brier'] for r in rs], '{:.3f}')} | {ms([r['health'][det]['holdout_ece'] for r in rs], '{:.3f}')} |")
    top = rs[0]["shap_global_top"][:5]
    lines += ["", "Top SHAP drivers of predicted RUL (seed " + str(seeds[0]) + ", test set): " + "; ".join(f"`{t['feature']}` ({t['description']})" for t in top), ""]
    alarm_ev = {sp: [r["alarms"]["gbm_rul"]["min_cost"][sp] for r in rs] for sp in ("test", "holdout")}
    table = [
        {"metric": "RUL RMSE — gradient boosting (cycles)", "test": ms([r["gbm"]["test_rmse"] for r in rs]), "holdout": ms([r["gbm"]["holdout_rmse_all_cycles"] for r in rs])},
        {"metric": "RUL RMSE — 1D-CNN (cycles)", "test": ms([r["cnn"]["test_rmse"] for r in rs]), "holdout": ms([r["cnn"]["holdout_rmse_all_cycles"] for r in rs])},
        {"metric": "PHM08 score — gradient boosting", "test": ms([r["gbm"]["test_phm08"] for r in rs], "{:.0f}"), "holdout": "–"},
        {"metric": "Alarm detection rate", "test": ms([e["detection_rate"] for e in alarm_ev["test"]], "{:.0f}", pct=True), "holdout": ms([e["detection_rate"] for e in alarm_ev["holdout"]], "{:.0f}", pct=True)},
        {"metric": "False-alarm rate (engines)", "test": ms([e["false_alarm_rate"] for e in alarm_ev["test"]], "{:.0f}", pct=True), "holdout": ms([e["false_alarm_rate"] for e in alarm_ev["holdout"]], "{:.0f}", pct=True)},
        {"metric": "Median warning before failure (cycles)", "test": ms([e["median_lead_cycles"] for e in alarm_ev["test"]], "{:.0f}"), "holdout": ms([e["median_lead_cycles"] for e in alarm_ev["holdout"]], "{:.0f}")},
        {"metric": "P10–P90 interval coverage (nominal 80%)", "test": ms([r["gbm"]["test_p10_p90_coverage"] for r in rs], "{:.0f}", pct=True), "holdout": "–"},
    ]
    summary[subset] = {
        "table": table,
        "seeds": seeds,
        "gbm_test_rmse": float(np.mean([r["gbm"]["test_rmse"] for r in rs])),
        "cnn_test_rmse": float(np.mean([r["cnn"]["test_rmse"] for r in rs])),
        "gbm_test_phm08": float(np.mean([r["gbm"]["test_phm08"] for r in rs])),
        "alarm_test_detection": float(np.mean([r["alarms"]["gbm_rul"]["min_cost"]["test"]["detection_rate"] for r in rs])),
        "alarm_test_far": float(np.mean([r["alarms"]["gbm_rul"]["min_cost"]["test"]["false_alarm_rate"] for r in rs])),
        "alarm_test_median_lead": float(np.nanmean([r["alarms"]["gbm_rul"]["min_cost"]["test"]["median_lead_cycles"] for r in rs])),
    }
Path("results/RESULTS.md").write_text("\n".join(lines) + "\n")
Path("results/summary.json").write_text(json.dumps(summary, indent=2))
print("\n".join(lines))
