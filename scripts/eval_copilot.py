"""Evaluate the copilot on data/eval/copilot_qa.jsonl (questions written from the corpus documents).

Retrieval: a hit is relevant if it is from the gold source+page AND contains the gold key phrase.
Reports hit@k / MRR@10 for dense, BM25, hybrid (RRF) and hybrid + cross-encoder rerank, refusal accuracy on
out-of-scope questions, and answer faithfulness (key fact present, citations valid, sentence support).
Writes results/copilot_eval.json and results/COPILOT.md.
"""
import json
import re
from pathlib import Path

import numpy as np

from turbowatch.rag import Copilot, Retriever, tokenize

qa = [json.loads(line) for line in Path("data/eval/copilot_qa.jsonl").read_text().splitlines() if line.strip()]
ans_q = [e for e in qa if e["source"]]
oos_q = [e for e in qa if not e["source"]]
r = Retriever("data/corpus")  # production retriever: hybrid + cross-encoder rerank


def relevant(c, e):
    return c["source"] == e["source"] and c["page"] == e["page"] and e["key"].lower() in c["text"].lower()


def rankings(e, depth=20):
    q = r.embedder.encode([e["q"]], query=True)[0]
    dense = r.emb @ q
    sparse = r.bm25.get_scores(tokenize(e["q"]))
    d = list(np.argsort(-dense)[:depth])
    s = list(np.argsort(-sparse)[:depth])
    hyb = [h.chunk for h in r._hybrid(e["q"], depth, 40, 60)]
    return {"dense": [r.chunks[i] for i in d], "bm25": [r.chunks[i] for i in s], "hybrid": hyb}


from sentence_transformers import CrossEncoder  # noqa: E402

ce = CrossEncoder("cross-encoder/ms-marco-MiniLM-L6-v2", device="cpu")
stats = {m: {"hit@1": [], "hit@3": [], "hit@5": [], "mrr@10": []} for m in ("dense", "bm25", "hybrid", "hybrid+rerank")}
for e in ans_q:
    rk = rankings(e)
    cands = rk["hybrid"][:20]
    sc = ce.predict([(e["q"], c["text"]) for c in cands], show_progress_bar=False)
    rk["hybrid+rerank"] = [cands[i] for i in np.argsort(-np.asarray(sc))]
    for m, lst in rk.items():
        rel = [relevant(c, e) for c in lst[:10]]
        for k in (1, 3, 5):
            stats[m][f"hit@{k}"].append(float(any(rel[:k])))
        stats[m]["mrr@10"].append(next((1 / (i + 1) for i, x in enumerate(rel) if x), 0.0))
retrieval = {m: {k: float(np.mean(v)) for k, v in d.items()} for m, d in stats.items()}

# refusal score: top cross-encoder logit, answerable vs out-of-scope
def top_score(q):
    return float(r.search(q, k=1)[0].rerank)
md_ans = [top_score(e["q"]) for e in ans_q]
md_oos = [top_score(e["q"]) for e in oos_q]

cop = Copilot(r)
answers = []
for e in qa:
    out = cop.answer(e["q"])
    cited_text = " ".join(c["snippet"] for c in out["citations"])
    full = {c["id"]: c for c in r.chunks}
    cited_full = " ".join(full[c["id"]]["text"] for c in out["citations"])
    sents = [s for s in re.split(r"(?<=[.!?])\s+", re.sub(r"\[\d+\]", "", out["answer"])) if len(tokenize(s)) >= 3]
    support = [np.mean([t in set(tokenize(cited_full)) for t in tokenize(s)]) >= 0.8 for s in sents] if sents else [False]
    nums = [int(n) for n in re.findall(r"\[(\d+)\]", out["answer"])]
    answers.append({"q": e["q"], "in_scope": bool(e["source"]), "mode": out["mode"],
                    "key_in_answer": bool(e["key"]) and e["key"].lower() in out["answer"].lower(),
                    "key_in_citations": bool(e["key"]) and any(e["key"].lower() in full[c["id"]]["text"].lower() for c in out["citations"]),
                    "citations_valid": all(1 <= n <= len(out["citations"]) for n in nums) and (bool(nums) or out["mode"] == "refusal"),
                    "sentence_support": float(np.mean(support)), "refused": out["mode"] == "refusal", "answer": out["answer"][:400]})
    del cited_text

ins = [a for a in answers if a["in_scope"]]
oos = [a for a in answers if not a["in_scope"]]
mode = ins[0]["mode"] if ins else "n/a"
res = {
    "n_questions": len(qa), "n_in_scope": len(ins), "n_out_of_scope": len(oos), "answer_mode": mode,
    "retrieval": retrieval,
    "refusal_threshold_rerank_logit": cop.min_rerank, "top_rerank_in_scope_min": min(md_ans), "top_rerank_out_of_scope_max": max(md_oos),
    "in_scope_answered": float(np.mean([not a["refused"] for a in ins])),
    "out_of_scope_refused": float(np.mean([a["refused"] for a in oos])),
    "key_fact_in_answer": float(np.mean([a["key_in_answer"] for a in ins])),
    "key_fact_in_cited_passages": float(np.mean([a["key_in_citations"] for a in ins])),
    "citations_valid": float(np.mean([a["citations_valid"] for a in ins if not a["refused"]])),
    "sentence_support": float(np.mean([a["sentence_support"] for a in ins if not a["refused"]])),
    "answers": answers,
}
Path("results").mkdir(exist_ok=True)
Path("results/copilot_eval.json").write_text(json.dumps(res, indent=2))
pct = lambda x: f"{100 * x:.0f}%"  # noqa: E731
md = ["# Copilot evaluation (generated by `scripts/eval_copilot.py`)", "",
      f"{len(ins)} questions written from the corpus documents (gold = source page + key phrase) and {len(oos)} out-of-scope questions. "
      f"Answer mode evaluated: **{mode}** ({'Groq LLM' if mode == 'llm' else 'extractive template fallback — no API key in the evaluation run'}).", "",
      "## Retrieval (in-scope questions)", "", "| Retriever | hit@1 | hit@3 | hit@5 | MRR@10 |", "|---|---|---|---|---|"]
for m, d in retrieval.items():
    md.append(f"| {m} | {pct(d['hit@1'])} | {pct(d['hit@3'])} | {pct(d['hit@5'])} | {d['mrr@10']:.3f} |")
md += ["", "## Answers", "", "| Metric | Value |", "|---|---|",
       f"| In-scope questions answered (not refused) | {pct(res['in_scope_answered'])} |",
       f"| Out-of-scope questions refused | {pct(res['out_of_scope_refused'])} |",
       f"| Gold key fact present in the cited passages | {pct(res['key_fact_in_cited_passages'])} |",
       f"| Gold key fact present in the answer text | {pct(res['key_fact_in_answer'])} |",
       f"| Answers whose citation markers point to retrieved passages | {pct(res['citations_valid'])} |",
       f"| Answer sentences supported by cited passages (≥80% content-word overlap) | {pct(res['sentence_support'])} |", "",
       f"Refusal rule: refuse when the reranker's top logit < {cop.min_rerank} (the cross-encoder's own 50% relevance point — not tuned on this set). "
       f"Lowest in-scope top logit: {min(md_ans):.2f}; highest out-of-scope: {max(md_oos):.2f}. With only 4 out-of-scope questions, treat the refusal rate as indicative.",
       "Production retriever = hybrid + rerank (bge-small-en-v1.5 dense + BM25, reciprocal rank fusion, ms-marco-MiniLM-L-6-v2 cross-encoder on the top 20).", ""]
Path("results/COPILOT.md").write_text("\n".join(md))
print("\n".join(md))
