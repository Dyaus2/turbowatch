"""Regime/fault-mode shift scenario: a model trained on FD001 (HPC degradation only) meets FD003 engines
(HPC + fan degradation, same operating condition). Shows (1) PSI drift detection on the stream and
(2) a champion/challenger decision: retrain on FD001+FD003 fit engines and promote only if the challenger
wins on CALIBRATION engines of BOTH fleets (no regression on the original fleet). Reported numbers are on
held-out test sets. Writes results/DRIFT.md and results/drift.json.
"""
import json
from pathlib import Path

import pandas as pd

from turbowatch import data, metrics
from turbowatch.drift import DriftMonitor
from turbowatch.features import FeaturePipeline, capped, last_rows
from turbowatch.models.gbm import GBMRul
from turbowatch.split import split_engines

SEED, CAP, TOL = 0, 125, 0.5  # challenger may not be worse than champion by > TOL RMSE on the old fleet
d1, d3 = data.load("FD001"), data.load("FD003")


def prep(sub, offset):
    tr = sub.train.copy()
    tr["unit"] += offset
    te = sub.test.copy()
    te["unit"] += offset
    s = split_engines(tr["unit"].unique(), seed=SEED)
    return tr, te, s


tr1, te1, s1 = prep(d1, 0)
tr3, te3, s3 = prep(d3, 1000)


def rul_eval(fp, gbm, train_df, split, test_df, rul_test):
    cal = split.frame(train_df, "calib").sort_values(["unit", "cycle"]).reset_index(drop=True)
    Xc = fp.transform(cal)
    yc = capped(data.add_true_rul(cal), CAP)
    Xt = last_rows(fp.transform(test_df))
    yt = capped(rul_test, CAP)
    return {"calib_rmse": metrics.rmse(yc, gbm.predict(Xc)), "test_rmse": metrics.rmse(yt, gbm.predict(Xt)),
            "test_phm08": metrics.phm08(yt, gbm.predict(Xt))}


def fit(train_frames):
    fit_df = pd.concat(train_frames, ignore_index=True)
    fp = FeaturePipeline(seed=SEED).fit(fit_df)
    X = fp.transform(fit_df)
    srt = fit_df.sort_values(["unit", "cycle"]).reset_index(drop=True)
    return fp, GBMRul(seed=SEED).fit(X[fp.feature_names], capped(data.add_true_rul(srt), CAP))


# champion: FD001 only (same protocol as the main pipeline)
fp_c, champ = fit([s1.frame(tr1, "fit")])
# drift: reference = HEALTHY baseline = first 30 cycles of the FD001 fit engines (normalised).
# Streams: first 30 cycles (healthy phase) and last 30 observed cycles (degraded phase) of each test fleet.
early = lambda df: df[df["cycle"] <= 30]  # noqa: E731
mon = DriftMonitor(fp_c.normalise(early(s1.frame(tr1, "fit"))), fp_c.sensors_)
psi_fd001 = mon.report(fp_c.normalise(early(te1)))
psi_fd003 = mon.report(fp_c.normalise(early(te3)))
late = lambda df: df.groupby("unit").tail(30)  # noqa: E731
psi_fd003_late = mon.report(fp_c.normalise(late(te3)))
psi_fd001_late = mon.report(fp_c.normalise(late(te1)))

# challenger: retrained on FD001 + FD003 fit engines
fp_n, chal = fit([s1.frame(tr1, "fit"), s3.frame(tr3, "fit")])
ev = {
    "champion": {"FD001": rul_eval(fp_c, champ, tr1, s1, te1, d1.rul_test), "FD003": rul_eval(fp_c, champ, tr3, s3, te3, d3.rul_test)},
    "challenger": {"FD001": rul_eval(fp_n, chal, tr1, s1, te1, d1.rul_test), "FD003": rul_eval(fp_n, chal, tr3, s3, te3, d3.rul_test)},
}
c, n = ev["champion"], ev["challenger"]
promote = n["FD003"]["calib_rmse"] < c["FD003"]["calib_rmse"] and n["FD001"]["calib_rmse"] <= c["FD001"]["calib_rmse"] + TOL
res = {"psi_fd001_early": psi_fd001, "psi_fd003_early": psi_fd003, "psi_fd001_late": psi_fd001_late, "psi_fd003_late": psi_fd003_late,
       "evaluation": ev, "decision": "promote challenger" if promote else "keep champion", "tolerance_rmse": TOL}
Path("results/drift.json").write_text(json.dumps(res, indent=2))

top = lambda rep: ", ".join(f"{d['sensor']} {d['psi']:.2f}" for d in rep[:4])  # noqa: E731
n_alert = lambda rep: sum(d["level"] == "alert" for d in rep)  # noqa: E731
md = ["# Drift & champion/challenger scenario (generated by `scripts/drift_scenario.py`)", "",
      "Champion = gradient-boosting RUL model trained on FD001 fit engines (HPC degradation, one operating condition). "
      "New fleet = FD003 (HPC **and fan** degradation, same operating condition).", "",
      "## Drift detection (PSI per sensor vs the healthy FD001 baseline = first 30 cycles of FD001 training engines; ≥0.25 = alert)", "",
      "| Stream window | Sensors in alert | Top PSI |", "|---|---|---|",
      f"| FD001 test, first 30 cycles (in-distribution) | {n_alert(psi_fd001)} / {len(psi_fd001)} | {top(psi_fd001)} |",
      f"| FD003 test, first 30 cycles (new fleet, healthy phase) | {n_alert(psi_fd003)} / {len(psi_fd003)} | {top(psi_fd003)} |",
      f"| FD001 test, last 30 observed cycles | {n_alert(psi_fd001_late)} / {len(psi_fd001_late)} | {top(psi_fd001_late)} |",
      f"| FD003 test, last 30 observed cycles | {n_alert(psi_fd003_late)} / {len(psi_fd003_late)} | {top(psi_fd003_late)} |", "",
      "Sensors in alert in the degraded FD003 stream but **not** in the degraded FD001 stream (new failure signature the champion never saw): "
      + (", ".join(sorted({d['sensor'] for d in psi_fd003_late if d['level'] == 'alert'} - {d['sensor'] for d in psi_fd001_late if d['level'] == 'alert'})) or "none") + ".", "",
      "## Champion vs challenger (challenger retrained on FD001 + FD003 fit engines)", "",
      "| Model | FD001 calib RMSE | FD003 calib RMSE | FD001 test RMSE | FD003 test RMSE |", "|---|---|---|---|---|",
      f"| Champion (FD001 only) | {c['FD001']['calib_rmse']:.2f} | {c['FD003']['calib_rmse']:.2f} | {c['FD001']['test_rmse']:.2f} | {c['FD003']['test_rmse']:.2f} |",
      f"| Challenger (FD001 + FD003) | {n['FD001']['calib_rmse']:.2f} | {n['FD003']['calib_rmse']:.2f} | {n['FD001']['test_rmse']:.2f} | {n['FD003']['test_rmse']:.2f} |", "",
      f"Decision rule (calibration engines only): promote if the challenger is better on FD003 and not worse than the champion by more than {TOL} RMSE on FD001. "
      f"**Decision: {res['decision']}.** Test columns are reported after the decision, for transparency.", ""]
Path("results/DRIFT.md").write_text("\n".join(md))
print("\n".join(md))
